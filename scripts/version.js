#!/usr/bin/env node
// App version management. VERSION (semver) is the single source of truth; it is
// stamped into the binary (-ldflags) and into web/js/version.js for the UI.
//
//   node scripts/version.js                       print the version
//   node scripts/version.js check                 VERSION, version.js and CHANGELOG agree
//   node scripts/version.js bump patch|minor|major|X.Y.Z ["change note" ...]
//        moves "Unreleased" notes (plus any given) into a dated release section
//   node scripts/version.js sync                  regenerate web/js/version.js
'use strict';

const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const VERSION_FILE = path.join(root, 'VERSION');
const JS_FILE = path.join(root, 'web', 'js', 'version.js');
const CHANGELOG = path.join(root, 'CHANGELOG.md');
const SEMVER = /^(\d+)\.(\d+)\.(\d+)$/;

const read = () => fs.readFileSync(VERSION_FILE, 'utf8').trim();
const jsFor = (v) => `// Generated by scripts/version.js from VERSION. Do not edit.\n'use strict';\nvar APP_VERSION = '${v}';\n`;
const die = (msg) => { console.error(msg); process.exit(1); };

function check() {
  const v = read();
  if (!SEMVER.test(v)) die(`VERSION "${v}" is not semver X.Y.Z`);
  const js = fs.existsSync(JS_FILE) ? fs.readFileSync(JS_FILE, 'utf8') : '';
  if (js !== jsFor(v)) die(`web/js/version.js does not match VERSION ${v}: run "node scripts/version.js sync"`);
  const log = fs.readFileSync(CHANGELOG, 'utf8');
  if (!log.includes(`## [${v}]`)) die(`CHANGELOG.md has no "## [${v}]" section: run "make bump"`);
  console.log(`version ${v} OK`);
}

function next(cur, part) {
  if (SEMVER.test(part)) return part;
  const [, a, b, c] = SEMVER.exec(cur).map(Number);
  if (part === 'major') return `${a + 1}.0.0`;
  if (part === 'minor') return `${a}.${b + 1}.0`;
  if (part === 'patch') return `${a}.${b}.${c + 1}`;
  return die(`bump: expected patch | minor | major | X.Y.Z, got "${part}"`);
}

function bump(part, notes) {
  const cur = read();
  const v = next(cur, part || 'patch');
  const cmp = (x, y) => { const p = x.split('.').map(Number), q = y.split('.').map(Number); return p[0] - q[0] || p[1] - q[1] || p[2] - q[2]; };
  if (cmp(v, cur) <= 0) die(`bump: ${v} is not newer than ${cur}`);
  let log = fs.readFileSync(CHANGELOG, 'utf8');
  const head = '## [Unreleased]';
  const i = log.indexOf(head);
  if (i < 0) die('CHANGELOG.md is missing the "## [Unreleased]" section');
  const rest = log.slice(i + head.length);
  const j = rest.search(/\n## \[/);
  const pending = (j < 0 ? rest : rest.slice(0, j)).trim();
  const bullets = [pending, ...notes.map((n) => '- ' + n)].filter(Boolean).join('\n');
  if (!bullets) die('bump: nothing to release; add notes under "## [Unreleased]" in CHANGELOG.md or pass them as arguments');
  const date = new Date().toISOString().slice(0, 10);
  log = log.slice(0, i) + `${head}\n\n## [${v}] - ${date}\n\n${bullets}\n` + (j < 0 ? '' : rest.slice(j));
  fs.writeFileSync(CHANGELOG, log);
  fs.writeFileSync(VERSION_FILE, v + '\n');
  fs.writeFileSync(JS_FILE, jsFor(v));
  console.log(`${cur} -> ${v}`);
}

const [cmd, ...args] = process.argv.slice(2);
if (!cmd) console.log(read());
else if (cmd === 'check') check();
else if (cmd === 'sync') { fs.writeFileSync(JS_FILE, jsFor(read())); console.log('web/js/version.js ->', read()); }
else if (cmd === 'bump') bump(args[0], args.slice(1));
else die(`unknown command "${cmd}"`);
